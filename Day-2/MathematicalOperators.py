# Basic Mathematical Operators

print(123+345)
print(7-3)
print(9*6)
print(5/3) # Implicit Type Casting : Division operator '/' implicitly converts into float.
print(5//3) # this Division operator returns the answer in int.
print(2**3) # Exponent - 2^3

# Order of calculation in Python- PEMDAS : Parenthesis, Exponents, Multiplication/Division, Addition/Subtraction (for same priority operations Left one will be executed first)

print(3*3+3/3-3)